-- PostgreSQL schema for CioOkul. Applied by database.apply_postgres_schema() on every start,
-- so every statement must stay idempotent. Column order matches the SQLite tables because
-- several INSERT statements use positional VALUES.
--
-- Timestamps stay TEXT in SQLite's UTC format ('YYYY-MM-DD HH:MM:SS') so the JSON the
-- browser receives is identical on both backends. database.py rewrites CURRENT_TIMESTAMP
-- in queries to cio_now().

-- Helpers that give PostgreSQL the SQLite behaviour the queries rely on.
CREATE OR REPLACE FUNCTION cio_now() RETURNS text LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

-- SQLite: date(value,'localtime'). The server clock is UTC, so the school's zone is explicit.
CREATE OR REPLACE FUNCTION local_date(value text) RETURNS text LANGUAGE sql STABLE AS
$$ SELECT to_char((value::timestamp AT TIME ZONE 'UTC') AT TIME ZONE 'Europe/Istanbul', 'YYYY-MM-DD') $$;

-- Same mapping as app.turkish_normalize (TR_MAP, then lower()).
CREATE OR REPLACE FUNCTION tr_norm(value text) RETURNS text LANGUAGE sql IMMUTABLE AS
$$ SELECT lower(translate(coalesce(value, ''), 'İIıŞşÇçĞğÖöÜüÂâÎîÛû', 'iiissccggoouuaaiiuu')) $$;

-- SQLite's json_each() over a JSON array stored as text; only j.value is used by the app.
CREATE OR REPLACE FUNCTION json_each(doc text) RETURNS TABLE(key integer, value text) LANGUAGE sql IMMUTABLE AS
$$ SELECT (t.position - 1)::integer, t.element FROM jsonb_array_elements_text(doc::jsonb) WITH ORDINALITY AS t(element, position) $$;

CREATE TABLE IF NOT EXISTS users (
  role TEXT PRIMARY KEY CHECK(role IN ('parent','student')),
  name TEXT NOT NULL,
  salt TEXT NOT NULL,
  secret_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS booklets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course TEXT NOT NULL,
  title TEXT NOT NULL,
  pdf_path TEXT NOT NULL,
  source_url TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booklet_id INTEGER NOT NULL REFERENCES booklets(id),
  number INTEGER NOT NULL,
  page INTEGER NOT NULL,
  kind TEXT NOT NULL,
  stem TEXT NOT NULL,
  answer_key TEXT NOT NULL,
  verified INTEGER NOT NULL DEFAULT 0,
  image_path TEXT,
  UNIQUE(booklet_id, number)
);
CREATE TABLE IF NOT EXISTS choices (
  question_id INTEGER NOT NULL REFERENCES questions(id),
  label TEXT NOT NULL,
  text TEXT NOT NULL,
  PRIMARY KEY(question_id, label)
);
CREATE TABLE IF NOT EXISTS assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT cio_now(),
  submitted_at TEXT,
  due_date TEXT,
  last_question_index INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS assignment_questions (
  assignment_id INTEGER NOT NULL REFERENCES assignments(id),
  question_id INTEGER NOT NULL REFERENCES questions(id),
  position INTEGER NOT NULL,
  PRIMARY KEY(assignment_id, question_id)
);
CREATE TABLE IF NOT EXISTS responses (
  assignment_id INTEGER NOT NULL,
  question_id INTEGER NOT NULL,
  choice TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT cio_now(),
  duration_seconds INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(assignment_id, question_id),
  FOREIGN KEY(assignment_id, question_id)
    REFERENCES assignment_questions(assignment_id, question_id)
);
CREATE TABLE IF NOT EXISTS reviews (
  assignment_id INTEGER NOT NULL,
  question_id INTEGER NOT NULL,
  grade TEXT NOT NULL CHECK(grade IN ('correct','incorrect','partial')),
  note TEXT NOT NULL DEFAULT '',
  reviewed_at TEXT NOT NULL DEFAULT cio_now(),
  PRIMARY KEY(assignment_id, question_id),
  FOREIGN KEY(assignment_id, question_id)
    REFERENCES assignment_questions(assignment_id, question_id)
);
CREATE TABLE IF NOT EXISTS question_flags (
  question_id INTEGER PRIMARY KEY REFERENCES questions(id),
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT cio_now()
);
CREATE TABLE IF NOT EXISTS plan_overrides (
  booklet_id INTEGER NOT NULL REFERENCES booklets(id),
  test_index INTEGER NOT NULL,
  year_month TEXT NOT NULL,
  PRIMARY KEY(booklet_id,test_index)
);
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS mistake_resolutions (
  kind TEXT NOT NULL,
  item_key TEXT NOT NULL,
  resolved_at TEXT NOT NULL DEFAULT cio_now(),
  PRIMARY KEY(kind, item_key)
);

CREATE TABLE IF NOT EXISTS reading_sections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  pages_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS reading_questions (
  section_id INTEGER NOT NULL REFERENCES reading_sections(id),
  number INTEGER NOT NULL,
  page INTEGER NOT NULL,
  image TEXT NOT NULL,
  kind TEXT NOT NULL,
  prompt TEXT NOT NULL,
  answer_key TEXT NOT NULL,
  answer_image TEXT NOT NULL,
  max_score INTEGER NOT NULL DEFAULT 1,
  options_json TEXT NOT NULL DEFAULT '[]',
  answer_page INTEGER NOT NULL DEFAULT 0,
  skill TEXT NOT NULL DEFAULT 'locate',
  PRIMARY KEY(section_id,number)
);
CREATE TABLE IF NOT EXISTS reading_assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id INTEGER NOT NULL REFERENCES reading_sections(id),
  title TEXT NOT NULL,
  due_date TEXT,
  created_at TEXT NOT NULL DEFAULT cio_now(),
  submitted_at TEXT,
  last_question_index INTEGER NOT NULL DEFAULT 0,
  question_numbers_json TEXT
);
CREATE TABLE IF NOT EXISTS reading_responses (
  assignment_id INTEGER NOT NULL REFERENCES reading_assignments(id),
  number INTEGER NOT NULL,
  answer TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT cio_now(),
  duration_seconds INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(assignment_id,number)
);
CREATE TABLE IF NOT EXISTS reading_reviews (
  assignment_id INTEGER NOT NULL REFERENCES reading_assignments(id),
  number INTEGER NOT NULL,
  score INTEGER NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  reviewed_at TEXT NOT NULL DEFAULT cio_now(),
  PRIMARY KEY(assignment_id,number)
);
CREATE TABLE IF NOT EXISTS reading_image_checks (
  section_id INTEGER NOT NULL,
  number INTEGER NOT NULL,
  side TEXT NOT NULL CHECK(side IN ('question','answer')),
  verified INTEGER NOT NULL DEFAULT 0,
  note TEXT NOT NULL DEFAULT '',
  updated_at TEXT NOT NULL DEFAULT cio_now(),
  PRIMARY KEY(section_id,number,side)
);

CREATE TABLE IF NOT EXISTS study_reflections (
  kind TEXT NOT NULL CHECK(kind IN ('test','reading')),
  assignment_id INTEGER NOT NULL,
  item_key TEXT NOT NULL,
  uncertain INTEGER NOT NULL DEFAULT 0,
  reason TEXT NOT NULL DEFAULT '',
  PRIMARY KEY(kind,assignment_id,item_key)
);
CREATE TABLE IF NOT EXISTS study_repeat_queue (
  kind TEXT NOT NULL CHECK(kind IN ('test','reading')),
  item_key TEXT NOT NULL,
  stage INTEGER NOT NULL DEFAULT 0,
  due_date TEXT NOT NULL,
  source_assignment_id INTEGER NOT NULL,
  assigned_assignment_id INTEGER,
  updated_at TEXT NOT NULL DEFAULT cio_now(),
  PRIMARY KEY(kind,item_key)
);

-- Login sessions; only a SHA-256 of the cookie token is stored. Not part of backups.
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  role TEXT NOT NULL CHECK(role IN ('parent','student')),
  expires_at INTEGER NOT NULL
);

